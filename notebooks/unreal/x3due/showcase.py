def url_of(entry: dict) -> str:
    if entry.get("url"):
        return entry["url"]
    return RAW.format(repo=entry["repo"], sha=entry["sha"], path=entry["path"])


def _get(url, dest: Path, timeout=120, tries=3) -> int:
    dest.parent.mkdir(parents=True, exist_ok=True)
    last = None
    for k in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "x3d.lab-unreal"})
            with urllib.request.urlopen(req, timeout=timeout) as r, open(dest, "wb") as fh:
                n = 0
                while True:
                    b = r.read(1 << 20)
                    if not b:
                        break
                    fh.write(b)
                    n += len(b)
            return n
        except Exception as exc:
            last = exc
            time.sleep(1 + 2 * k)
    raise last


URL_FIELDS = re.compile(r"\b(url|frontUrl|backUrl|leftUrl|rightUrl|topUrl|bottomUrl|groundUrl|skyUrl)\s*=\s*(['\"])(.*?)\2", re.S)


def relative_urls(xml: str) -> list[list[str]]:
    """Every url-type MFString in the file as a list of candidates (relative ones only; data:, http(s): dropped)."""
    out = []
    for m in URL_FIELDS.finditer(xml):
        raw = m.group(3).replace("&quot;", '"')
        cands = re.findall(r'"([^"]*)"', raw) or [raw]
        rel = [c for c in cands if c and not re.match(r"^(?:[a-z][a-z0-9+.-]*:|/|#)", c, re.I)]
        if rel:
            out.append(rel)
    return out


def fetch(name: str, dest_dir, log=print) -> dict:
    """Download one catalogue entry and the relative files it references. Returns {"main": path, "files": [...], "missing": [...]}."""
    e = CATALOGUE[name]
    dest = Path(dest_dir) / name
    dest.mkdir(parents=True, exist_ok=True)
    if e.get("generated"):
        p = dest / "calib.x3d"
        p.write_text(CALIB, encoding="utf-8")
        return {"main": str(p), "files": [str(p)], "missing": [], "bytes": len(CALIB)}
    url = url_of(e)
    main = dest / os.path.basename(urllib.parse.urlparse(url).path)
    n = _get(url, main)
    files, missing, total = [str(main)], [], n
    if e["kind"] == "x3d":
        xml = main.read_text(encoding="utf-8", errors="replace")
        for cands in relative_urls(xml):
            got = False
            for c in cands:
                target = (dest / c).resolve()
                if dest.resolve() not in target.parents:
                    continue
                if target.exists():
                    got = True
                    break
                try:
                    total += _get(urllib.parse.urljoin(url, urllib.parse.quote(c)), target)
                    files.append(str(target))
                    got = True
                    break
                except Exception:
                    continue
            if not got:
                missing.append(cands[0])
    log("%s: %d file(s), %.1f MB%s" % (name, len(files), total / 1e6, (", %d missing: %s" % (len(missing), ", ".join(missing[:5]))) if missing else ""))
    return {"main": str(main), "files": files, "missing": sorted(set(missing)), "bytes": total}


def licence_table(names) -> str:
    rows = ["| scene | input | licence | why it is here |", "|---|---|---|---|"]
    for n in names:
        e = CATALOGUE[n]
        rows.append("| %s | %s | %s | %s |" % (n, e["kind"], e["licence"], e["why"]))
    return "\n".join(rows)
